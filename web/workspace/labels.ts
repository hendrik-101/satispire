function recipeLabel(name: string): string | undefined {
  if (name.startsWith('Alternate: ')) {
    const translated = alternateNames[name.slice('Alternate: '.length)];
    return translated === undefined ? undefined : `Alternativ: ${translated}`;
  }
  if (name.startsWith('Unpackage ')) {
    const content = name.slice('Unpackage '.length);
    const translated = names[content === 'Oil' ? 'Crude Oil' : content];
    return translated === undefined ? undefined : `${translated} auspacken`;
  }
  const qualified = /^(.*) \((.*)\)$/.exec(name);
  if (qualified) {
    const product =
      names[qualified[1]! === 'Uranium Ore' ? 'Uranium' : qualified[1]!];
    const method =
      names[qualified[2]!] ??
      {
        Aluminum: 'Aluminium',
        Caterium: 'Caterium',
        Copper: 'Kupfer',
        Iron: 'Eisen',
        Quartz: 'Quarz',
        '1': '1',
        '2': '2',
        '5': '5',
      }[qualified[2]!];
    if (product !== undefined && method !== undefined)
      return `${product} (${method})`;
  }
  return recipeNames[name] ?? names[name];
}

const labels = new Map<string, string>();
for (const entry of [...vanillaCatalog.items, ...vanillaCatalog.machines]) {
  const label = names[entry.name];
  if (label !== undefined) labels.set(entry.id, label);
}
for (const recipe of vanillaCatalog.recipes) {
  const label = recipeLabel(recipe.name);
  if (label !== undefined) labels.set(recipe.id, label);
}

/** Presentation only: unknown/custom catalog names remain caller-controlled. */
export function localizedName(id: string, fallback?: string): string {
  return labels.get(id) ?? fallback ?? id;
}
